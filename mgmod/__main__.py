"""Command line: python3 -m mgmod {list,build,check,webpatch}."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

from . import card, ledger, registry, stock
from .module import BASE, MAX_IMAGE


def build(remix, image):
    ledger.check(remix['modules'])
    for module in remix['modules']:
        image = module.apply(image)
    if len(image) > MAX_IMAGE:
        raise ValueError('image too large for the SD updater')
    return image


def cmd_list(args):
    for m in registry.all_modules():
        print(f'{m.name:22s} {m.status:12s} {m.title}')
    print()
    for name in registry.all_remixes():
        r = registry.remix(name)
        print(f'remix {name}: {", ".join(m.name for m in r["modules"])}')


def cmd_build(args):
    remix = registry.remix(args.remix)
    image = build(remix, stock.load(args.firmware))
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(image).hexdigest()
    (out / 'mgmod.bin').write_bytes(card.card_file(image))
    (out / f'mg204-{remix["name"]}.bin').write_bytes(image)
    print(f'remix {remix["name"]}: {len(image)} bytes, sha256 {digest}')
    if remix.get('sha256') and remix['sha256'] != digest:
        print('warning: differs from the reference build recorded in the remix (toolchain difference?)')
    print(f'  {out / "mgmod.bin"}  -> copy to the card root (SD updater must already be installed)')
    if not args.no_wav:
        card.encode_wav(image, out / f'mg204-{remix["name"]}.wav')
        print(f'  {out / ("mg204-" + remix["name"] + ".wav")}  -> audio update (first install, or recovery)')
    print('Built from your own firmware: do not share these files.')


def cmd_check(args):
    """Reproducibility: every remix builds to its recorded sha256."""
    image = stock.load(args.firmware)
    ok = True
    for name in registry.all_remixes():
        remix = registry.remix(name)
        digest = hashlib.sha256(build(remix, image)).hexdigest()
        same = digest == remix.get('sha256')
        ok &= same
        print(f'{"PASS" if same else "FAIL"} {name} {digest}')
    return 0 if ok else 1


def cmd_webpatch(args):
    """Write web/remixes.js: for each remix, only the bytes this project wrote
    (runs that differ from stock, and the appended code), never stock bytes."""
    image = stock.load(args.firmware)
    docs = []
    for name in registry.all_remixes():
        remix = registry.remix(name)
        built = build(remix, image)
        runs, i = [], 0
        while i < len(built):
            if i < len(image) and built[i] == image[i]:
                i += 1
                continue
            j = i
            while j < len(built) and not (j < len(image) and built[j] == image[j]):
                j += 1
            runs.append([i, built[i:j].hex()])
            i = j
        doc = dict(name=name, title=remix['title'], description=remix['description'],
                   stock_sha256=stock.STOCK_SHA256, size=len(built),
                   sha256=hashlib.sha256(built).hexdigest(),
                   modules=[dict(name=m.name, title=m.title, status=m.status) for m in remix['modules']],
                   runs=runs)
        docs.append(doc)
        print(f'{name}: {len(runs)} runs, {sum(len(r[1]) // 2 for r in runs)} bytes')
    path = Path(__file__).resolve().parent.parent / 'web' / 'remixes.js'
    path.write_text('// Generated by `python3 -m mgmod webpatch`. Only bytes written by this project.\n'
                    'window.MGMOD_REMIXES = ' + json.dumps(docs) + ';\n')
    print(f'wrote {path}')


def main():
    parser = argparse.ArgumentParser(prog='python3 -m mgmod')
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('list', help='modules and remixes')
    b = sub.add_parser('build', help='build a remix from your own mg204 firmware')
    b.add_argument('remix')
    b.add_argument('--firmware', required=True, help='the official mg204.wav (or its decoded .bin)')
    b.add_argument('--output', default='build')
    b.add_argument('--no-wav', action='store_true', help='skip the audio update WAV')
    c = sub.add_parser('check', help='every remix reproduces its recorded sha256')
    c.add_argument('--firmware', required=True)
    w = sub.add_parser('webpatch', help='regenerate web/remixes.js for the web builder')
    w.add_argument('--firmware', required=True)
    args = parser.parse_args()
    return {'list': cmd_list, 'build': cmd_build, 'check': cmd_check, 'webpatch': cmd_webpatch}[args.command](args) or 0


if __name__ == '__main__':
    sys.exit(main())
